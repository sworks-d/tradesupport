def lookup(ticker: str, fallback: str = "") -> str:
    """ticker から日本語社名を返す。なければ fallback。

    >>> lookup("7203")
    'トヨタ自動車'
    >>> lookup("9999", fallback="Unknown Corp.")
    'Unknown Corp.'
    """
    return JP_COMPANY_NAMES.get(ticker, fallback or ticker)


def is_jp_ticker(ticker: str) -> bool:
    """4 桁数字の東証銘柄かどうか。"""
    return len(ticker) == 4 and ticker.isdigit()
